#!/usr/bin/env python3
"""T37 innovation comparison: the same real model and the same task, before and after T26.

T26 ("the approved save payload is generated by the program; the model only decides whether to save") is compared
with the commit before it. Each run uses a fresh official-seed SQLite database and a fresh local server, drives the
review-panel save through the real HTTP API, and judges the outcome from the database, never from model text.

Usage (JDK 21 and LLM_* variables set in the shell; nothing secret is written to the output):
    python3 scripts/innovation_compare.py --runs 5
    python3 scripts/innovation_compare.py --before-jar old.jar --after-jar new.jar --runs 10
Output: <out>/results.json, <out>/summary.md and one server log per run.
"""
import argparse, http.cookiejar, json, os, socket, sqlite3, subprocess, sys, tempfile, time, urllib.error, urllib.parse, urllib.request, uuid
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAR = "target/harness-0.0.1-SNAPSHOT.jar"
VALUE = "办公室采购"
QUERY = "查询 C001 2026 年 9 月的发票，并检查用途缺口"


def build(ref, workdir, repo_cache):
    """Build one git ref in its own detached worktree; the frontend is not needed for an API comparison."""
    tree = workdir / f"src-{ref}"
    subprocess.run(["git", "-C", str(ROOT), "worktree", "add", "--detach", str(tree), ref], check=True)
    subprocess.run(["mvn", "-q", "-DskipTests", "-Dfrontend.skip=true", f"-Dmaven.repo.local={repo_cache}", "package"],
                   cwd=tree, check=True)
    return tree, tree / JAR


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class Client:
    def __init__(self, base):
        self.base, self.csrf = base, None
        self.http = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, method, path, body=None, timeout=180):
        data = None if body is None else json.dumps(body, ensure_ascii=False).encode()
        request = urllib.request.Request(self.base + path, data=data, method=method)
        request.add_header("Content-Type", "application/json")
        if self.csrf: request.add_header("X-CSRF-Token", self.csrf)
        try:
            with self.http.open(request, timeout=timeout) as response:
                return response.status, json.loads(response.read() or b"null")
        except urllib.error.HTTPError as e:
            try: return e.code, json.loads(e.read() or b"null")
            except ValueError: return e.code, None


def scenario(base, pending):
    """Query, then the exact review-panel save of F002.purpose. Returns the evidence for one run."""
    c = Client(base)
    status, session = c.call("GET", "/api/demo/session"); c.csrf = session["csrfToken"]
    status, session = c.call("POST", "/api/demo/session", {"profile": "operator", "enterprise": "C001"})
    if status != 200: return {"stage": "session", "http": status, "errorCode": (session or {}).get("errorCode")}
    c.csrf = session["csrfToken"]
    status, task = c.call("POST", "/api/demo/tasks", {"goal": "查询九月发票并补齐 F002 用途", "pending": pending})
    if status != 200: return {"stage": "start", "http": status, "errorCode": (task or {}).get("errorCode")}
    started = time.time()
    status, first = c.call("POST", f"/api/demo/tasks/{task['id']}/turn", {"message": QUERY})
    query = {"http": status, "errorCode": code(first), "seconds": round(time.time() - started, 1), "tools": tools(first)}
    if code(first) == "MODEL_NOT_CONFIGURED": return {"stage": "query", "query": query, "errorCode": "MODEL_NOT_CONFIGURED"}
    # The same message and structured approval the React review panel sends.
    approval = {"operationId": str(uuid.uuid4()), "invoiceId": "F002", "changes": {"purpose": VALUE}, "confirmed": True}
    message = "现在保存以下经我逐项核对的精确修改，并查询发票核对：" + json.dumps(
        {"enterprise": "C001", "invoiceId": "F002", "changes": {"purpose": VALUE}}, ensure_ascii=False, indent=2)
    started = time.time()
    status, saved = c.call("POST", f"/api/demo/tasks/{task['id']}/turn", {"message": message, "approval": approval})
    verified = bool(((saved or {}).get("verification") or {}).get("verified"))
    return {"stage": "save", "query": query, "http": status, "errorCode": code(saved), "verified": verified,
            "seconds": round(time.time() - started, 1), "tools": tools(saved), "writeArguments": write_arguments(saved)}


def code(view):
    if not isinstance(view, dict): return "INVALID_RESPONSE"
    return view.get("errorCode") or ((view.get("turn") or {}).get("result") or {}).get("errorCode")


def history(view):
    return (((view or {}).get("turn") or {}).get("result") or {}).get("history") or []


def tools(view):
    return [e.get("call", {}).get("name") for e in history(view)]


def write_arguments(view):
    """What the model put in its update_invoice call(s): the difference T26 removes from the evidence path."""
    return [e.get("call", {}).get("arguments") for e in history(view) if e.get("call", {}).get("name") == "update_invoice"]


def database_state(db):
    with sqlite3.connect(db) as c:
        purpose = c.execute("SELECT purpose FROM invoices WHERE enterprise_id='C001' AND id='F002'").fetchone()[0]
        ledger = c.execute("SELECT count(*) FROM invoice_operations").fetchone()[0]
    return purpose, ledger


def run_once(jar, out, label, index, pending):
    work = Path(tempfile.mkdtemp(prefix=f"t37-{label}-"))
    db = work / "demo.db"
    subprocess.run(["java", "-jar", str(jar), "--initialize-data", f"--database={db}"], check=True,
                   stdout=subprocess.DEVNULL)
    port = free_port()
    log = (out / f"server-{label}-{index}.log").open("w")
    server = subprocess.Popen(["java", "-jar", str(jar), f"--taxagent.database={db}", "--server.address=127.0.0.1",
                               f"--server.port={port}"], stdout=log, stderr=subprocess.STDOUT)
    base = f"http://127.0.0.1:{port}"
    try:
        for _ in range(120):
            try:
                with urllib.request.urlopen(base + "/api/health", timeout=2) as r:
                    if r.status == 200: break
            except Exception: time.sleep(0.5)
        else:
            return {"stage": "health", "errorCode": "SERVER_NOT_READY"}
        result = scenario(base, pending)
    finally:
        server.terminate()
        try: server.wait(timeout=20)
        except subprocess.TimeoutExpired: server.kill()
        log.close()
    purpose, ledger = database_state(db)
    # Pass only on database evidence: the approved value is stored, exactly one ledger entry, verified read-back.
    result.update(purpose=purpose, ledger=ledger,
                  passed=result.get("verified") is True and purpose == VALUE and ledger == 1 and not result.get("errorCode"))
    return result


def summary(results, meta):
    lines = ["# T37 创新对比运行结果（自动生成，未经人工修改）", "",
             f"- 生成时间：{meta['generatedAt']}", f"- 模型：`{meta['model']}`，协议：`{meta['protocol']}`，端点主机：`{meta['endpointHost']}`",
             f"- 每组运行次数：{meta['runs']}；判定：数据库中 F002 用途等于批准值、台账恰好 1 条、回读 `verified=true` 且无错误码", "",
             "| 版本 | 待补字段 | 通过 / 运行 | 失败码分布 | 保存轮平均耗时（秒） |", "|---|---|---|---|---|"]
    for (label, pending), runs in results.items():
        passed = sum(1 for r in runs if r.get("passed"))
        failures = Counter((r.get("errorCode") or ("NOT_VERIFIED" if not r.get("passed") else None)) for r in runs if not r.get("passed"))
        times = [r["seconds"] for r in runs if isinstance(r.get("seconds"), (int, float))]
        lines.append(f"| {label} (`{meta['refs'][label]}`) | {','.join(pending)} | {passed} / {len(runs)} | "
                     f"{', '.join(f'{k}×{v}' for k, v in failures.items()) or '—'} | {round(sum(times) / len(times), 1) if times else '—'} |")
    lines += ["", "逐次明细（含模型 `update_invoice` 实际参数与工具序列）见 `results.json`。"]
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--before-ref", default="f7ffe68", help="commit before T26")
    p.add_argument("--after-ref", default="HEAD")
    p.add_argument("--before-jar"); p.add_argument("--after-jar")
    p.add_argument("--runs", type=int, default=5)
    p.add_argument("--pending", action="append",
                   help="pending fields for one variant, comma separated; repeatable (default: F002.purpose and F002.purpose,F002.remarks)")
    p.add_argument("--out", default=str(ROOT / "target" / "t37-innovation"))
    a = p.parse_args()
    for name in ("LLM_ENDPOINT", "LLM_API_KEY", "LLM_MODEL"):
        if not os.environ.get(name): sys.exit(f"{name} is not set; this comparison needs the real model")
    variants = [v.split(",") for v in (a.pending or ["F002.purpose", "F002.purpose,F002.remarks"])]
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="t37-build-"))
    trees, jars = [], {}
    try:
        for label, ref, jar in (("before", a.before_ref, a.before_jar), ("after", a.after_ref, a.after_jar)):
            if jar: jars[label] = Path(jar).resolve()
            else:
                tree, jars[label] = build(ref, work, ROOT / ".m2" / "repository"); trees.append(tree)
        results = {}
        for pending in variants:
            for label in ("before", "after"):
                runs = results.setdefault((label, tuple(pending)), [])
                for i in range(1, a.runs + 1):
                    r = run_once(jars[label], out, label, f"{'+'.join(pending)}-{i}", pending)
                    runs.append(r)
                    print(f"{label} {','.join(pending)} #{i}: {'PASS' if r.get('passed') else 'FAIL'} {r.get('errorCode') or ''}", flush=True)
                    if r.get("errorCode") == "MODEL_NOT_CONFIGURED": sys.exit("model not configured on the server; stopping")
        endpoint = os.environ["LLM_ENDPOINT"]
        meta = {"generatedAt": time.strftime("%Y-%m-%d %H:%M:%S %z"), "model": os.environ["LLM_MODEL"],
                "protocol": os.environ.get("LLM_PROTOCOL", "(by endpoint)"), "endpointHost": urllib.parse.urlparse(endpoint).hostname,
                "runs": a.runs, "refs": {"before": a.before_jar or a.before_ref, "after": a.after_jar or a.after_ref}}
        (out / "results.json").write_text(json.dumps({"meta": meta, "results": [
            {"version": label, "pending": list(pending), "runs": runs} for (label, pending), runs in results.items()]},
            ensure_ascii=False, indent=2), encoding="utf-8")
        (out / "summary.md").write_text(summary(results, meta), encoding="utf-8")
        print(f"written: {out / 'summary.md'}")
    finally:
        for tree in trees:
            subprocess.run(["git", "-C", str(ROOT), "worktree", "remove", "--force", str(tree)], check=False)


if __name__ == "__main__":
    main()
